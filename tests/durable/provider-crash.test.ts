const cleanup:Array<()=>Promise<unknown>>=[];
afterEach(async()=>{for(const fn of cleanup.splice(0).reverse())await fn();});
test('SIGKILL preserves a pending fast preference and command identity while native input recovers',async()=>{
 const path=await mkdtemp(join(tmpdir(),'native-provider-crash-'));cleanup.push(()=>rm(path,{recursive:true,force:true}));
 const cache=join(process.cwd(),'node_modules/.cache');await mkdir(cache,{recursive:true});const compiled=await mkdtemp(join(cache,'provider-crash-'));cleanup.push(()=>rm(compiled,{recursive:true,force:true}));
 await promisify(execFile)(process.execPath,['node_modules/typescript/bin/tsc','--strict','--skipLibCheck','--module','nodenext','--target','es2023','--rootDir','.', '--outDir',compiled,'src/durable/provider-fast.ts'],{timeout:30_000});
 const child=fork(join(process.cwd(),'tests/durable/provider-crash-worker.mjs'),[compiled,path],{stdio:['ignore','ignore','pipe','ipc']});
 let stderr='';child.stderr!.on('data',c=>stderr+=c);
 const exited=new Promise(resolve=>child.once('exit',(code,signal)=>resolve({code,signal})));
 cleanup.push(async()=>{if(child.exitCode===null&&child.signalCode===null)child.kill('SIGKILL');await exited;});
 await new Promise<void>((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error(`Pending preference not reached: ${stderr}`)),5000);child.on('message',m=>{if((m as {event:string}).event==='pending'){clearTimeout(timer);resolve();}});});
 child.kill('SIGKILL');expect(await exited).toMatchObject({signal:'SIGKILL'});
 const faux=fauxProvider();const hold=Promise.withResolvers<void>(),started=Promise.withResolvers<void>();
 faux.setResponses([async()=>{started.resolve();await hold.promise;return fauxAssistantMessage('RECOVERED');}]);
 const models=createModels();models.setProvider(faux.provider);let fast!:ReturnType<typeof createNativeFast>;
 const finals:string[]=[];
 const host=await DurableHost.create({stateDir:path,models,registry:createRegistry(),agent:{model:{provider:faux.provider.id,modelId:faux.getModel().id}},compatibility:{runtimeGeneration:'fixture',releaseSchema:1,profile:'fixture',registrySignature:'fixture'},policy(){},controlPolicy(){},beforeAdmission:async()=>fast.settle(),transport:{async start(){},async stop(){hold.resolve();},async sendFinal(r){finals.push(r.text);return {messageId:1};}}});
 cleanup.push(()=>host.close());
 fast=createNativeFast({host:()=>host,botId:123,model:async()=>openaiCodexProvider().getModels()[0]});
 expect(await host.runtime.harness.snapshot(NativeFast,host.runtime.root.id,context)).toMatchObject({active:false,saved:true});
 await host.start();await started.promise;
 expect(await fast.command('telegram-command:123:pending','on')).toContain('Pending:');expect(await fast.active()).toBe(false);
 hold.resolve();await vi.waitFor(()=>expect(finals).toEqual(['RECOVERED']));await host.reconcile();expect(await fast.active()).toBe(true);
 await fast.command('telegram-command:123:new','off');await fast.command('telegram-command:123:pending','on');expect(await fast.active()).toBe(false);
},40_000);
